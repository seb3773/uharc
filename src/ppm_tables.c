static int ppm_isqrt(int x)
{
    int r = 0;
    while ((r + 1) * (r + 1) <= x)
        r++;
    return r;
}

static int ppm_bucket(const int *thr, int hi, int i)
{
    int v, res = 0;
    for (v = 0; v <= hi; v++)
        if (thr[v] <= i)
            res = v;
    return res;
}

void uha_ppm_gen_tables(void)
{
    static int done;
    int i, j, v, m;
    int fib[9];
    int T2[16];
    int rthr[13];
    int fthr[11];
    static const int THR_43A590[7] = {0, 4, 8, 14, 24, 40, 64};
    static const int THR_PAGETAB[7] = {0, 2, 4, 6, 10, 16, 30};
    static const uint8_t LZPC_BASE[8] = {11, 11, 24, 11, 6, 6, 11, 6};
    static const uint8_t LZPC_CAP[8]  = {14, 14, 24, 14, 9, 9, 11, 9};

    if (done)
        return;
    done = 1;

    PPMS_F154[0] = 0;
    for (i = 1; i < 16384; i++)
        PPMS_F154[i] = (uint16_t)(65520 - (int)ceil(4680.0 * log((double)i) / log(2.0)));

    for (i = 0; i < 17; i++) {
        if (i < 2)
            PPMS_RANKBASE_L[i] = 0;
        else
            PPMS_RANKBASE_L[i] = (uint32_t)(255 + i * (i - 1) / 2);
    }
    for (i = 0; i < 5; i++)
        PPMS_RANKBASE_S[i] = PPMS_RANKBASE_L[i];

    for (i = 0; i < 256; i++) {
        j = i;
        if (256 - i < j)
            j = 256 - i;
        PPMS_S7BankC[i] = j >> 3;
        PPMS_S7BankD[i] = j >> 6;
    }
    for (i = 0; i < 512; i++) {
        j = i;
        if (512 - i < j)
            j = 512 - i;
        if (j == 0)
            PPMS_CandBucket9[i] = 0;
        else
            PPMS_CandBucket9[i] = ppm_isqrt(j - 1) + 1;
    }

    fib[0] = 1; fib[1] = 1;
    for (i = 2; i < 9; i++)
        fib[i] = fib[i - 1] + fib[i - 2];

    T2[0] = 0;
    for (v = 1; v <= 8; v++)
        T2[v] = T2[v - 1] + fib[v];
    T2[9] = 170;
    for (v = 10; v <= 15; v++)
        T2[v] = T2[v - 1] + fib[8 - (v - 10)];
    for (i = 0; i < 256; i++)
        PPMS_SelTab2[i] = (uint8_t)ppm_bucket(T2, 15, i);

    for (v = 0; v <= 5; v++)
        rthr[v] = v;
    rthr[6] = 7;
    for (v = 7; v <= 12; v++)
        rthr[v] = rthr[v - 1] + fib[v - 4];
    fthr[0] = 166;
    fthr[1] = fthr[0] + fib[8]; fthr[2] = fthr[1] + fib[7];
    fthr[3] = fthr[2] + fib[6]; fthr[4] = fthr[3] + fib[5];
    fthr[5] = fthr[4] + fib[4]; fthr[6] = fthr[5] + fib[3];
    fthr[7] = fthr[6] + fib[2]; fthr[8] = fthr[7] + fib[1];
    fthr[9] = fthr[8] + fib[0]; fthr[10] = fthr[9] + 1;
    for (i = 0; i < 256; i++) {
        if (i < 91)
            PPMS_MMCost[i] = (uint32_t)ppm_bucket(rthr, 12, i);
        else if (i <= 165)
            PPMS_MMCost[i] = 12;
        else
            PPMS_MMCost[i] = (uint32_t)(11 - ppm_bucket(fthr, 10, i));
    }

    for (i = 0; i < 256; i++)
        PPMS_43A590[i] = (uint32_t)ppm_bucket(THR_43A590, 6, i);
    for (i = 0; i < 288; i++)
        PPMS_PAGETAB[i] = (uint32_t)ppm_bucket(THR_PAGETAB, 6, i);

    for (i = 0; i < 256; i++) {
        PPMS_REC1THR[i] = 125;
        PPMS_REC2THR[i] = 125;
    }
    for (i = 0; i < 5; i++) {
        PPMS_REC1THR[i] = 253;
        PPMS_REC2THR[i] = 247;
    }
    PPMS_REC1THR[5] = 221; PPMS_REC1THR[6] = 157;
    PPMS_REC2THR[5] = 217; PPMS_REC2THR[6] = 155;

    for (i = 0; i <= 81; i++) {
        if (i < 80) {
            v = LZPC_BASE[i / 10] + (i % 10);
            if (v > LZPC_CAP[i / 10])
                v = LZPC_CAP[i / 10];
        } else if (i == 80)
            v = 49;
        else
            v = 79;
        j = i * 8;
        PPMS_LZPCLASS_INIT[j]     = 0;
        PPMS_LZPCLASS_INIT[j + 1] = 0;
        PPMS_LZPCLASS_INIT[j + 2] = 1;
        PPMS_LZPCLASS_INIT[j + 3] = 0;
        PPMS_LZPCLASS_INIT[j + 4] = (uint8_t)v;
        PPMS_LZPCLASS_INIT[j + 5] = 0;
        PPMS_LZPCLASS_INIT[j + 6] = 0x63;
        PPMS_LZPCLASS_INIT[j + 7] = 0;
    }

    for (i = 0; i < 64; i++) {
        if (i == 0)
            v = 256;
        else {
            v = 4;
            m = i;
            while ((m & 1) == 0) {
                v <<= 1;
                m >>= 1;
            }
        }
        j = i * 4;
        PPMS_ROWSEED[j]     = (uint16_t)v;
        PPMS_ROWSEED[j + 1] = 1;
        PPMS_ROWSEED[j + 2] = 2;
        PPMS_ROWSEED[j + 3] = 1;
    }
}

